// Headless Chromium check of `web/serve.py --https --lan`: a page reached over a LAN address is a
// secure context (so WebGPU exists) only with HTTPS; the self-signed certificate is rejected without
// the user clicking through; Range requests work over TLS in the browser.
//
//   node web/tests/https_browser_test.mjs
//
// Needs Playwright (default path below, override with PLAYWRIGHT_MODULE), Chromium (CHROMIUM_PATH) and
// a non-loopback IPv4 address on this machine (otherwise the LAN checks are skipped).
import fs from 'node:fs';
import net from 'node:net';
import os from 'node:os';
import path from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const webDir = path.resolve(here, '..');
const pw = await import(process.env.PLAYWRIGHT_MODULE
  ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href
  : '/opt/node-tools/node_modules/playwright/index.mjs');
const { chromium } = pw.default ?? pw;

let failures = 0;
const check = (cond, msg) => { console.log((cond ? 'PASS ' : 'FAIL ') + msg); if (!cond) failures++; };

const freePort = () => new Promise((resolve) => {
  const s = net.createServer().listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); });
});
const lanIp = Object.values(os.networkInterfaces()).flat().find((i) => i && i.family === 'IPv4' && !i.internal)?.address;
console.log(`LAN address: ${lanIp ?? '(none)'}`);

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'wc-https-'));
const site = path.join(tmp, 'site');
fs.mkdirSync(site);
fs.writeFileSync(path.join(site, 'index.html'), '<!doctype html><title>https test</title><body>ok</body>');
const payload = Buffer.from(Array.from({ length: 4096 }, (_, i) => i & 255));
fs.writeFileSync(path.join(site, 'blob.bin'), payload);

// Certificates: one generated by serve.py itself (openssl when present), one by the pure-Python generator.
const pyCerts = path.join(tmp, 'py-certs');
const gen = spawnSync('python3', ['-c',
  'import sys; sys.path.insert(0, sys.argv[1]); import selfsigned_cert as c; r = c.ensure_certificate(sys.argv[2], backend="python"); print(r.cert_path); print(r.key_path)',
  webDir, pyCerts], { encoding: 'utf8' });
check(gen.status === 0, 'pure-Python certificate generated ' + (gen.stderr || ''));
const [pyCert, pyKey] = gen.stdout.trim().split('\n');

const servers = [];
async function start(args) {
  const port = await freePort();
  const child = spawn('python3', [path.join(webDir, 'serve.py'), '--dir', site, '--port', String(port), '-q', ...args],
    { stdio: ['ignore', 'pipe', 'inherit'] });
  servers.push(child);
  let out = '';
  child.stdout.on('data', (d) => { out += d; });
  for (let i = 0; i < 100 && !/Open on this computer/.test(out); i++) await new Promise((r) => setTimeout(r, 100));
  return { port, out: () => out };
}

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium',
  args: ['--enable-unsafe-webgpu', '--use-angle=swiftshader', '--no-sandbox', '--no-proxy-server'],
});

async function probe(url, ignoreHTTPSErrors) {
  const ctx = await browser.newContext({ ignoreHTTPSErrors });
  const page = await ctx.newPage();
  try {
    await page.goto(url, { timeout: 15000 });
    const info = await page.evaluate(async () => {
      const r = await fetch('blob.bin', { headers: { Range: 'bytes=10-19' } });
      return {
        secure: window.isSecureContext,
        gpu: typeof navigator.gpu,
        proto: location.protocol,
        status: r.status,
        range: r.headers.get('Content-Range'),
        bytes: Array.from(new Uint8Array(await r.arrayBuffer())),
      };
    });
    return { info };
  } catch (e) {
    return { error: String(e.message || e) };
  } finally {
    await ctx.close();
  }
}

try {
  const generated = await start(['--https', '--lan', '--cert-dir', path.join(tmp, 'certs'), '--san', 'game.example']);
  const own = await start(['--lan', '--cert', pyCert, '--key', pyKey]);
  const plain = await start(['--lan']);
  console.log(generated.out());
  check(/SHA-256 fingerprint/.test(generated.out()) && /not private/.test(generated.out()), 'serve.py explains the browser warning and prints the fingerprint');
  check(!/Certificate:/.test(own.out()), 'a user-supplied --cert is used as is (nothing generated)');

  const hosts = lanIp ? [lanIp, 'localhost'] : ['localhost'];
  for (const [label, server] of [['generated (openssl if present)', generated], ['--cert/--key from the pure-Python generator', own]]) {
    for (const host of hosts) {
      const url = `https://${host}:${server.port}/`;
      const bad = await probe(url, false);
      check(bad.error && /ERR_CERT/.test(bad.error), `${label}: ${host}: untrusted certificate is refused until the user proceeds (${(bad.error || '').split('\n')[0]})`);
      const ok = await probe(url, true);
      check(ok.info && ok.info.secure === true && ok.info.gpu === 'object' && ok.info.proto === 'https:',
        `${label}: ${host}: page is a secure context with navigator.gpu after proceeding (${JSON.stringify(ok.info && { secure: ok.info.secure, gpu: ok.info.gpu })})`);
      check(ok.info && ok.info.status === 206 && ok.info.range === 'bytes 10-19/4096' && ok.info.bytes.join() === Array.from(payload.subarray(10, 20)).join(),
        `${label}: ${host}: Range request over TLS from the page`);
    }
  }
  if (lanIp) {
    const http = await probe(`http://${lanIp}:${plain.port}/`, false);
    check(http.info && http.info.secure === false && http.info.gpu === 'undefined',
      `plain http on the LAN address is NOT a secure context and has no navigator.gpu (${JSON.stringify(http.info && { secure: http.info.secure, gpu: http.info.gpu })})`);
  } else {
    console.log('SKIP no LAN address: http-vs-https secure-context comparison');
  }
} catch (e) {
  console.log('FAIL unexpected exception: ' + (e && e.stack || e));
  failures++;
}
console.log(failures ? `${failures} FAILED` : 'ALL PASSED');
for (const s of servers) s.kill();
fs.rmSync(tmp, { recursive: true, force: true });
process.exit(failures ? 1 : 0);
